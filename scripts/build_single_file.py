#!/usr/bin/env python3
"""Concatenate src/dbml_atlas/ into a single self-contained dbml_atlas.py.

Usage:
    python scripts/build_single_file.py          # writes dbml_atlas.py
    python scripts/build_single_file.py --check  # verify hash matches committed file
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
SRC = ROOT / "src" / "dbml_atlas"
OUT = ROOT / "dbml_atlas.py"

# Modules in dependency order (each imports only from modules listed before it)
MODULES = ["model", "style", "parser", "layout", "routing", "render_svg", "render_html", "pdf", "introspect", "suggest", "cli"]


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _strip_local_imports(src: str) -> str:
    """Remove `from .X import Y` lines — everything will be in one namespace."""
    return re.sub(r"^from \.[^\n]+\n", "", src, flags=re.MULTILINE)


def _strip_future_import(src: str) -> str:
    return re.sub(r"^from __future__ import annotations\n", "", src, flags=re.MULTILINE)


def _inline_viewer_assets(src: str) -> str:
    """Replace _load("viewer.css") and _load("viewer.js") with inline strings."""
    for asset in ("viewer.css", "viewer.js"):
        content = _read(SRC / "viewer" / asset).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        src = src.replace(f'_load("{asset}")', f'"""{content}"""')
    # Remove the _HERE and _load() helper since assets are now inline
    src = re.sub(r"_HERE = Path\(__file__\)\.parent\n", "", src)
    src = re.sub(r"def _load\(name: str\) -> str:.*?\n\n", "", src, flags=re.DOTALL)
    # Remove pathlib import from render_html section (still needed globally if used elsewhere)
    return src


def build() -> str:
    parts = [
        "#!/usr/bin/env python3",
        '"""dbml-atlas — single-file build (generated by scripts/build_single_file.py).',
        "Edit src/dbml_atlas/ and regenerate. Do not edit this file directly.",
        '"""',
        "from __future__ import annotations",
        "",
        # Collect all stdlib imports (deduplicated)
    ]

    stdlib_imports: set[str] = set()
    module_bodies: list[str] = []

    for mod in MODULES:
        src = _read(SRC / f"{mod}.py")
        src = _strip_future_import(src)
        # Collect stdlib imports (single and multi-line)
        for line in src.splitlines():
            if re.match(r"^import |^from (?!\.)(?!dbml_atlas)", line):
                stdlib_imports.add(line)
        # Strip all import statements including multi-line parenthetical forms
        src = re.sub(r"^from [^\n]+\([^)]*\)", "", src, flags=re.MULTILINE | re.DOTALL)
        src = re.sub(r"^(?:import |from ).*\n", "", src, flags=re.MULTILINE)
        src = _strip_local_imports(src)
        src = src.strip()
        if src:
            module_bodies.append(f"# ── {mod} ────────────────────────────────────────────────────────────────\n" + src)

    parts.extend(sorted(stdlib_imports))
    parts.append("")
    parts.extend(module_bodies)

    # Add __main__ entry point
    parts.extend([
        "",
        'if __name__ == "__main__":',
        "    main()",
    ])

    result = "\n".join(parts) + "\n"
    # Inline viewer assets
    result = _inline_viewer_assets(result)
    return result


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify hash matches committed dbml_atlas.py")
    a = ap.parse_args()

    content = build()

    if a.check:
        if not OUT.exists():
            sys.exit(f"Missing {OUT} — run without --check to generate it first.")
        committed = _read(OUT)
        if sha256(content) != sha256(committed):
            sys.exit("FAIL: dbml_atlas.py is out of date. Run: python scripts/build_single_file.py")
        print("OK: dbml_atlas.py is up to date.")
        return

    OUT.write_text(content, encoding="utf-8")
    print(f"Written {OUT}  ({len(content):,} bytes)")


if __name__ == "__main__":
    main()
