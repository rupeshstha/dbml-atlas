from __future__ import annotations

from collections import Counter, defaultdict

from .model import Schema
from .style import AREA_PALETTE


def suggest_groups(sc: Schema) -> str:
    """
    Analyse table names and FK relationships to suggest TableGroup blocks.

    Algorithm:
    1. Prefix clustering — tables sharing the same leading snake_case segment(s) form a group.
       Two-segment prefixes are tried first (e.g. "shop_staff" + "shop_notes" → "Shop"),
       then one-segment as a fallback.
    2. FK affinity — tables that didn't land in a prefix group attach to whichever existing
       group they share the most FK edges with.
    3. Connected components — any tables still ungrouped are clustered by FK reachability.
       Each component is named after its most-connected member.
    4. Output — ready-to-paste DBML TableGroup blocks with palette colours.
    """
    tables = list(sc.tables.keys())
    if not tables:
        return "// No tables found.\n"

    # Undirected FK adjacency (both child→parent and parent→child)
    adj: dict[str, set[str]] = defaultdict(set)
    for r in sc.refs:
        if r.child in sc.tables and r.parent in sc.tables:
            adj[r.child].add(r.parent)
            adj[r.parent].add(r.child)

    # ── 1. Prefix clustering ──────────────────────────────────────────────────
    # Try two-segment prefixes first so "plan_addon_prices" and "plan_addons"
    # both land in "Plan Addon" rather than just "Plan", when that's more specific.
    assigned: dict[str, str] = {}   # table → group name
    groups: dict[str, list[str]] = {}  # group name → [tables]

    for n_segs in (2, 1):
        prefix_map: dict[str, list[str]] = defaultdict(list)
        for name in tables:
            if name in assigned:
                continue
            parts = name.split("_")
            if len(parts) >= n_segs:
                prefix_map["_".join(parts[:n_segs])].append(name)

        for prefix, members in sorted(prefix_map.items()):
            unassigned = [m for m in members if m not in assigned]
            if len(unassigned) >= 2:
                g = prefix.replace("_", " ").title()
                if g not in groups:
                    groups[g] = []
                groups[g].extend(unassigned)
                for m in unassigned:
                    assigned[m] = g

    # ── 2. FK affinity ────────────────────────────────────────────────────────
    # Single tables not caught by prefix → attach to the group with the most
    # shared FK edges.  Do multiple passes until no more can be attached.
    changed = True
    while changed:
        changed = False
        for t in [t for t in tables if t not in assigned]:
            scores: Counter[str] = Counter()
            for nb in adj[t]:
                if nb in assigned:
                    scores[assigned[nb]] += 1
            if scores:
                best = scores.most_common(1)[0][0]
                groups[best].append(t)
                assigned[t] = best
                changed = True

    # ── 3. Connected components of remaining ungrouped ────────────────────────
    ungrouped = [t for t in tables if t not in assigned]
    if ungrouped:
        ug_set = set(ungrouped)
        visited: set[str] = set()
        for start in ungrouped:
            if start in visited:
                continue
            comp: list[str] = []
            stack = [start]
            while stack:
                node = stack.pop()
                if node in visited:
                    continue
                visited.add(node)
                if node in ug_set:
                    comp.append(node)
                    for nb in adj[node]:
                        if nb in ug_set and nb not in visited:
                            stack.append(nb)
            if not comp:
                continue
            # Name after the member with the most FK connections in the whole graph
            rep = max(comp, key=lambda t: len(adj[t]))
            g = rep.split("_")[0].title()
            base, n = g, 2
            while g in groups:
                g = f"{base}{n}"
                n += 1
            groups[g] = sorted(comp)
            for t in comp:
                assigned[t] = g

    # ── 4. Emit DBML ──────────────────────────────────────────────────────────
    lines = [
        "// Suggested TableGroups — generated by: dbml-atlas suggest-groups <file>",
        "// Review group names, adjust nesting with __ (e.g. Sales__Orders),",
        "// then paste into your DBML file.",
        "",
    ]
    for i, (g_name, members) in enumerate(groups.items()):
        color = AREA_PALETTE[i % len(AREA_PALETTE)]
        # DBML group names can't have spaces — use underscores, path separator stays __
        dbml_name = g_name.replace(" ", "_")
        lines.append(f'TableGroup {dbml_name} [color: "{color}"] {{')
        for m in sorted(members):
            lines.append(f"  {m}")
        lines.append("}")
        lines.append("")

    return "\n".join(lines)
